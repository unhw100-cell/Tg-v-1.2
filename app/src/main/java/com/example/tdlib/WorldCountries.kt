    fun matchByDialCode(dialDigits: String): CountryItem? {
        val normalized = if (dialDigits.startsWith("+")) dialDigits else "+${dialDigits.trim()}"
        return when (normalized) {
            "+1" -> all.find { it.code == "US" }
            "+7" -> all.find { it.code == "RU" }
            "+44" -> all.find { it.code == "GB" }
            "+39" -> all.find { it.code == "IT" }
            "+61" -> all.find { it.code == "AU" }
            "+358" -> all.find { it.code == "FI" }
            "+47" -> all.find { it.code == "NO" }
            "+590" -> all.find { it.code == "GP" }
            "+599" -> all.find { it.code == "CW" }
            "+262" -> all.find { it.code == "RE" }
            else -> all.find { it.dialCode == normalized }
        }
    }
